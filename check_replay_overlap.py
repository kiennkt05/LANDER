def analyze_overlap(exp5_selected, fedcbdr_selected, fedcbdr_mult=None, client_pool_sizes=None):
    """
    Compute overlap metrics between Exp5 and FedCBDR selections.

    Parameters:
      exp5_selected: {task: {client: [local_ids]}}
      fedcbdr_selected: {task: {client: [local_ids]}}
      fedcbdr_mult: {task: {client: {local_id: count}}} (optional)
      client_pool_sizes: {task: {client: pool_size}} (optional, for random chance baseline)
    """
    tasks = sorted(set(exp5_selected.keys()) | set(fedcbdr_selected.keys()))
    if not tasks:
        print("[!] No overlapping tasks found between the two sets of records.")
        return

    print("=" * 88)
    print(" REPLAY ITEM OVERLAP ANALYSIS: Exp5a-Global vs FedCBDR (repo_local)")
    print("=" * 88)

    grand_exp5_total = 0
    grand_fedcbdr_unique = 0
    grand_overlap = 0
    grand_fedcbdr_draws = 0
    grand_draws_on_exp5 = 0

    for task in tasks:
        e_clients = exp5_selected.get(task, {})
        f_clients = fedcbdr_selected.get(task, {})
        clients = sorted(set(e_clients.keys()) | set(f_clients.keys()))

        print(f"\n--- Task {task} ---")
        header = f"{'Client':<8} | {'Exp5a':<7} | {'FedCBDR':<8} | {'Overlap':<7} | {'Jaccard':<8} | {'% of Exp5':<10} | {'% of Fed':<10}"
        if fedcbdr_mult:
            header += f" | {'Draws on Exp5':<14}"
        if client_pool_sizes and task in client_pool_sizes:
            header += f" | {'Random Exp.':<11}"
        print(header)
        print("-" * len(header))

        task_exp5_unique = set()
        task_fedcbdr_unique = set()
        task_overlap_unique = set()
        task_draws = 0
        task_draws_on_exp5 = 0

        for k in clients:
            e_set = set(e_clients.get(k, []))
            f_set = set(f_clients.get(k, []))
            intersect = e_set & f_set
            union = e_set | f_set

            jaccard = (len(intersect) / len(union) * 100.0) if union else 0.0
            pct_exp5 = (len(intersect) / len(e_set) * 100.0) if e_set else 0.0
            pct_fed = (len(intersect) / len(f_set) * 100.0) if f_set else 0.0

            row = f"Client {k:<1} | {len(e_set):<7} | {len(f_set):<8} | {len(intersect):<7} | {jaccard:>6.2f}% | {pct_exp5:>8.2f}% | {pct_fed:>8.2f}%"

            if fedcbdr_mult and task in fedcbdr_mult and k in fedcbdr_mult[task]:
                mult_k = fedcbdr_mult[task][k]
                k_draws = sum(mult_k.values())
                k_hits = sum(mult_k[j] for j in intersect if j in mult_k)
                draw_hit_pct = (k_hits / k_draws * 100.0) if k_draws else 0.0
                row += f" | {k_hits}/{k_draws} ({draw_hit_pct:>5.1f}%)"
                task_draws += k_draws
                task_draws_on_exp5 += k_hits

            if client_pool_sizes and task in client_pool_sizes and k in client_pool_sizes[task]:
                nk = client_pool_sizes[task][k]
                exp_rand = (len(e_set) * len(f_set)) / nk if nk else 0.0
                row += f" | {exp_rand:>6.2f} (N={nk})"

            print(row)

            for j in e_set:
                task_exp5_unique.add((k, j))
            for j in f_set:
                task_fedcbdr_unique.add((k, j))
            for j in intersect:
                task_overlap_unique.add((k, j))

        t_union = task_exp5_unique | task_fedcbdr_unique
        t_jaccard = (len(task_overlap_unique) / len(t_union) * 100.0) if t_union else 0.0
        t_pct_exp5 = (len(task_overlap_unique) / len(task_exp5_unique) * 100.0) if task_exp5_unique else 0.0
        t_pct_fed = (len(task_overlap_unique) / len(task_fedcbdr_unique) * 100.0) if task_fedcbdr_unique else 0.0

        print("-" * len(header))
        t_summary = f"{'Total':<8} | {len(task_exp5_unique):<7} | {len(task_fedcbdr_unique):<8} | {len(task_overlap_unique):<7} | {t_jaccard:>6.2f}% | {t_pct_exp5:>8.2f}% | {t_pct_fed:>8.2f}%"
        if fedcbdr_mult and task_draws > 0:
            t_draw_pct = (task_draws_on_exp5 / task_draws * 100.0)
            t_summary += f" | {task_draws_on_exp5}/{task_draws} ({t_draw_pct:>5.1f}%)"
        print(t_summary)

        grand_exp5_total += len(task_exp5_unique)
        grand_fedcbdr_unique += len(task_fedcbdr_unique)
        grand_overlap += len(task_overlap_unique)
        grand_fedcbdr_draws += task_draws
        grand_draws_on_exp5 += task_draws_on_exp5

    # Overall Summary
    print("\n" + "=" * 88)
    print(" OVERALL MULTI-TASK SUMMARY")
    print("=" * 88)
    grand_union = grand_exp5_total + grand_fedcbdr_unique - grand_overlap
    g_jaccard = (grand_overlap / grand_union * 100.0) if grand_union else 0.0
    g_pct_exp5 = (grand_overlap / grand_exp5_total * 100.0) if grand_exp5_total else 0.0
    g_pct_fed = (grand_overlap / grand_fedcbdr_unique * 100.0) if grand_fedcbdr_unique else 0.0

    print(f"Total Unique Replay Items Selected by Exp5a-Global : {grand_exp5_total}")
    print(f"Total Unique Replay Items Selected by FedCBDR       : {grand_fedcbdr_unique}")
    print(f"Identical Items Selected by BOTH Methods           : {grand_overlap}")
    print(f"Overall Jaccard Similarity                         : {g_jaccard:.2f}%")
    print(f"Overlap % of Exp5a-Global Pool                     : {g_pct_exp5:.2f}%")
    print(f"Overlap % of FedCBDR Pool                          : {g_pct_fed:.2f}%")
    if grand_fedcbdr_draws > 0:
        g_draw_pct = (grand_draws_on_exp5 / grand_fedcbdr_draws * 100.0)
        print(f"FedCBDR Draws Landing on Exp5a Candidates         : {grand_draws_on_exp5}/{grand_fedcbdr_draws} ({g_draw_pct:.2f}%)")
    print("=" * 88)


