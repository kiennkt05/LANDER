#!/usr/bin/env python3
"""
check_replay_overlap.py
-----------------------
Inspect and quantify the overlap of selected replay items between:
  1) Exp5a-Global (--method=exp5a_global)
  2) FedCBDR     (--method=fedcbdr --gdr_protocol repo_local --tts_mode repo_dual)

WITHOUT MODIFYING ANY EXISTING REPOSITORY CODE.

Modes of operation:
-------------------
1. Parse Mode (Post-run / Offline):
   Compares the automatically generated Exp5 JSONL diagnostic log with the FedCBDR
   stdout log (or redirected log file).
   Usage:
     python check_replay_overlap.py --mode parse \
       --fedcbdr_log fedcbdr.log \
       --exp5_jsonl exp5_greedy_diag_1.0_exp5a_global_exp5a_global_seed2023.jsonl

2. In-Memory Runner Mode:
   Runs both experiments in sequence, dynamically intercepting selection via
   temporary runtime monkey-patching (without modifying files on disk), saving the
   exact selected candidate indices to JSON, and reporting the overlap.
   Usage:
     python check_replay_overlap.py --mode run \
       --dataset cifar10 --tasks 3 --num_users 5 --beta 1.0 --seed 2023 --gpu 0
"""

