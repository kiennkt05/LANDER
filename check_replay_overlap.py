def parse_exp5_jsonl(jsonl_path):
    """
    Parse the JSONL diagnostic file generated by Exp5a.
    Returns:
      selected: dict of {task_id: {client_id: list of local_candidate_ids}}
      details: dict of {task_id: {client_id: {local_candidate_id: dict of info}}}
    """
    if not os.path.exists(jsonl_path):
        raise FileNotFoundError(f"Exp5 JSONL file not found at: {jsonl_path}")

    selected = defaultdict(lambda: defaultdict(list))
    details = defaultdict(lambda: defaultdict(dict))

    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue

            if rec.get("type") == "step":
                task = int(rec["task"])
                client = int(rec["client"])
                local_cand = int(rec["local_candidate"])
                selected[task][client].append(local_cand)
                details[task][client][local_cand] = {
                    "global_candidate": rec.get("global_candidate"),
                    "label": rec.get("label"),
                    "step": rec.get("step"),
                    "phase": rec.get("phase"),
                }

    return selected, details


def parse_fedcbdr_log(log_path):
    """
    Parse FedCBDR stdout log to extract GDR multiplicities.
    Line format from methods/fedcbdr.py line 1181:
      Task <T> GDR draws=<D> unique=<U> p_sum=<P> multiplicities={<dict>} sampling_matrix_norm=<N>

    Returns:
      selected: dict of {task_id: {client_id: list of unique local_candidate_ids}}
      multiplicities: dict of {task_id: {client_id: {local_candidate_id: draw_count}}}
    """
    if not os.path.exists(log_path):
        raise FileNotFoundError(f"FedCBDR log file not found at: {log_path}")

    with open(log_path, "r", encoding="utf-8", errors="replace") as f:
        content = f.read()

    pattern = re.compile(
        r"Task\s+(\d+)\s+GDR\s+draws=\d+\s+unique=\d+.*?multiplicities=(\{.*?\})\s+sampling_matrix_norm",
        re.DOTALL
    )

    selected = defaultdict(lambda: defaultdict(list))
    multiplicities = defaultdict(lambda: defaultdict(dict))

    matches = pattern.findall(content)
    for task_str, mult_str in matches:
        task = int(task_str)
        try:
            mult_dict = ast.literal_eval(mult_str)
        except Exception as e:
            print(f"[Warning] Failed to parse multiplicities for task {task}: {e}")
            continue

        for (client_id, local_id), count in mult_dict.items():
            client_id = int(client_id)
            local_id = int(local_id)
            selected[task][client_id].append(local_id)
            multiplicities[task][client_id][local_id] = int(count)

    return selected, multiplicities


