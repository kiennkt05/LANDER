def main():
    parser = argparse.ArgumentParser(description="Check replay overlap between Exp5a-Global and FedCBDR.")
    parser.add_argument("--mode", type=str, choices=["parse", "run"], default="parse",
                        help="'parse' for existing logs/JSONL, 'run' to execute both methods in sequence")
    parser.add_argument("--exp5_jsonl", type=str, default=None,
                        help="Path to exp5_greedy_diag_*.jsonl file")
    parser.add_argument("--fedcbdr_log", type=str, default=None,
                        help="Path to fedcbdr stdout log file")

    args = parser.parse_args()

    if args.mode == "run":
        run_and_capture()
        return

    # In parse mode:
    # Auto-detect exp5 jsonl if not provided
    exp5_file = args.exp5_jsonl
    if not exp5_file:
        candidates = glob.glob("exp5_greedy_diag_*exp5a_global*seed2023*.jsonl")
        if candidates:
            exp5_file = candidates[0]
            print(f"[Auto-detected Exp5 JSONL] {exp5_file}")
        else:
            candidates_any = glob.glob("exp5_greedy_diag_*.jsonl")
            if candidates_any:
                exp5_file = candidates_any[0]
                print(f"[Auto-detected Exp5 JSONL] {exp5_file}")

    fedcbdr_file = args.fedcbdr_log
    if not fedcbdr_file:
        for fname in ["fedcbdr.log", "fedcbdr_output.txt", "fedcbdr.txt"]:
            if os.path.exists(fname):
                fedcbdr_file = fname
                print(f"[Auto-detected FedCBDR log] {fedcbdr_file}")
                break

    if not exp5_file or not fedcbdr_file:
        print("\n[!] Please specify the input files:")
        print("    --exp5_jsonl  <path_to_exp5_diag.jsonl>")
        print("    --fedcbdr_log <path_to_fedcbdr.log>")
        print("\nExample:")
        print("    python check_replay_overlap.py --mode parse \\\n"
              "      --exp5_jsonl exp5_greedy_diag_1.0_exp5a_global_exp5a_global_seed2023.jsonl \\\n"
              "      --fedcbdr_log fedcbdr.log\n")
        sys.exit(1)

    print(f"Loading Exp5 selections from   : {exp5_file}")
    exp5_selected, exp5_details = parse_exp5_jsonl(exp5_file)

    print(f"Loading FedCBDR selections from: {fedcbdr_file}")
    fedcbdr_selected, fedcbdr_mult = parse_fedcbdr_log(fedcbdr_file)

    analyze_overlap(exp5_selected, fedcbdr_selected, fedcbdr_mult)


if __name__ == "__main__":
    main()
